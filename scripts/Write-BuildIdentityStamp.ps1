param(
    [Parameter(Mandatory = $true)][string]$RepositoryRoot,
    [Parameter(Mandatory = $true)][string]$OutputPath,
    [Parameter(Mandatory = $true)][string]$ProductVersion,
    [AllowEmptyString()][string]$SourceRevisionId = ''
)

$ErrorActionPreference = 'Stop'
$root = [System.IO.Path]::GetFullPath($RepositoryRoot)
$root = $root.TrimEnd([System.IO.Path]::DirectorySeparatorChar, [System.IO.Path]::AltDirectorySeparatorChar)
$rootUri = [Uri]::new($root + [System.IO.Path]::DirectorySeparatorChar)

function Get-RelativePath([string]$FullPath) {
    return [Uri]::UnescapeDataString($rootUri.MakeRelativeUri([Uri]::new($FullPath)).ToString()).Replace('/', '/')
}

function ConvertTo-LowerHex([byte[]]$Bytes) {
    return ([BitConverter]::ToString($Bytes) -replace '-', '').ToLowerInvariant()
}

function Escape-CSharpString([string]$Value) {
    return $Value.Replace('\', '\\').Replace('"', '\"').Replace("`r", '\r').Replace("`n", '\n').Replace("`t", '\t')
}

function Get-FileSha256([string]$Path) {
    $algorithm = [System.Security.Cryptography.SHA256]::Create()
    try { return ConvertTo-LowerHex $algorithm.ComputeHash([System.IO.File]::ReadAllBytes($Path)) }
    finally { $algorithm.Dispose() }
}

function Invoke-GitText([string[]]$Arguments) {
    $lines = & git -C $root @Arguments 2>$null
    if ($LASTEXITCODE -ne 0) { return $null }
    return ($lines -join "`n").Trim()
}

$commit = Invoke-GitText @('rev-parse', '--verify', 'HEAD^{commit}')
$knownGit = $commit -match '^[0-9a-fA-F]{40}$'
if (-not $knownGit) { $commit = '' }

$excludedSegments = @('.git', 'bin', 'obj', 'work', 'archive', 'private', '.gemini-tasks')
$inputFiles = [System.Collections.Generic.List[string]]::new()
foreach ($area in @('LogForesight.Core', 'LogForesight.Web')) {
    $areaPath = Join-Path $root $area
    if (-not (Test-Path -LiteralPath $areaPath -PathType Container)) { continue }
    foreach ($file in Get-ChildItem -LiteralPath $areaPath -File -Recurse -Force) {
        $relative = Get-RelativePath $file.FullName
        $parts = $relative.Split('/')
        if ($parts | Where-Object { $excludedSegments -contains $_ }) { continue }
        if ($relative -match '^LogForesight\.Web/wwwroot/lib/') { continue }
        $inputFiles.Add($file.FullName)
    }
}
foreach ($name in @('Directory.Build.props', 'Directory.Build.targets', 'global.json', 'LogForesight.sln', 'NuGet.Config')) {
    $path = Join-Path $root $name
    if (Test-Path -LiteralPath $path -PathType Leaf) { $inputFiles.Add($path) }
}
foreach ($path in @(
    (Join-Path $root 'scripts/Write-BuildIdentityStamp.ps1'),
    (Join-Path $root 'scripts/build-identity/BuildIdentityManifest.csproj'),
    (Join-Path $root 'scripts/build-identity/Program.cs'),
    (Join-Path $root 'scripts/Verify-BuildIdentity.ps1')
)) {
    if (Test-Path -LiteralPath $path -PathType Leaf) { $inputFiles.Add($path) }
}

$entries = foreach ($fullPath in ($inputFiles | Sort-Object -Unique)) {
    $relative = Get-RelativePath $fullPath
    $digest = Get-FileSha256 $fullPath
    "$relative`n$digest`n"
}
$fingerprintBytes = [System.Text.Encoding]::UTF8.GetBytes(($entries -join ''))
$sha = [System.Security.Cryptography.SHA256]::Create()
try { $fingerprint = ConvertTo-LowerHex $sha.ComputeHash($fingerprintBytes) }
finally { $sha.Dispose() }

$status = Invoke-GitText @('status', '--porcelain', '--untracked-files=all', '--', 'LogForesight.Core', 'LogForesight.Web', 'Directory.Build.props', 'Directory.Build.targets', 'global.json', 'LogForesight.sln', 'NuGet.Config', 'scripts/Write-BuildIdentityStamp.ps1', 'scripts/build-identity', 'scripts/Verify-BuildIdentity.ps1')
$dirty = -not [string]::IsNullOrWhiteSpace($status)
$gitState = if ($knownGit) { if ($dirty) { 'modified' } else { 'clean' } } else { 'unknown' }
$stamp = "lfbuild-v1|$gitState|$commit|$fingerprint"
$baseVersion = ($ProductVersion -split '\+', 2)[0]
$informationalVersion = if ($knownGit) { "$baseVersion+$commit" } else { "$baseVersion+unknown.$fingerprint" }

$outputDirectory = Split-Path -Parent $OutputPath
if (-not (Test-Path -LiteralPath $outputDirectory)) { New-Item -ItemType Directory -Path $outputDirectory -Force | Out-Null }
$escaped = Escape-CSharpString $stamp
$escapedInformationalVersion = Escape-CSharpString $informationalVersion
$escapedOverride = Escape-CSharpString $SourceRevisionId
$source = @"
// Generated by Write-BuildIdentityStamp.ps1. Do not edit.
[assembly: System.Reflection.AssemblyInformationalVersionAttribute("$escapedInformationalVersion")]
[assembly: System.Reflection.AssemblyMetadataAttribute("LogForesight.BuildIdentity", "$escaped")]
[assembly: System.Reflection.AssemblyMetadataAttribute("LogForesight.BuildSourceRevisionIdOverride", "$escapedOverride")]
"@
if ((Test-Path -LiteralPath $OutputPath -PathType Leaf) -and
    [string]::Equals([System.IO.File]::ReadAllText($OutputPath), $source, [StringComparison]::Ordinal)) {
    return
}
[System.IO.File]::WriteAllText($OutputPath, $source, [System.Text.UTF8Encoding]::new($false))
